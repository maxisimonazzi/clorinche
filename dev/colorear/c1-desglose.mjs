// Corrección 1 — desglose de tiempos síncronos (CPU x4): carga del dibujo, balde grande y guardado.
import { launch, appUrl } from '../lib.mjs';
import { ready } from '../review-colorear/common.mjs';
const rate = +(process.argv[2] || 4);
const t = await launch({ size: 'tablet' });
const { page } = t;
const cdp = await page.context().newCDPSession(page);
await page.goto(appUrl('colorear/dragon'));
await ready(page);
await page.waitForTimeout(500);
await cdp.send('Emulation.setCPUThrottlingRate', { rate });
const r = await page.evaluate(async () => {
  const m = {};
  const time = async (k, fn) => { const t0 = performance.now(); const v = await fn(); m[k] = Math.round(performance.now() - t0); return v; };
  const src = await time('loadSource', () => CL.coloring.loadSource('dragon', 2048));
  const lines = await time('rasterLines', () => CL.coloring.rasterLines(src.image, src.w, src.h));
  const reg = await time('regions', () => CL.regions.computeAsync(lines));
  m.etapas = reg.timings;
  const p = await time('createPainter', () => CL.coloring.createPainter({ w: src.w, h: src.h, regions: reg, lines }));
  await time('maskFondo', () => CL.regions.mask(reg, reg.bg));
  await time('fillsSparkle2048', () => CL.fills.make('sparkle', '#8a4fdf', 2048, 2048, { unit: 1 }));
  await time('fillsSparkle2048_2', () => CL.fills.make('sparkle', '#8a4fdf', 2048, 2048, { unit: 1 }));
  await time('fillAtFondoSinAnim', () => p.fillAt(10, 10, { kind: 'sparkle', color: '#8a4fdf' }, { animate: false }));
  await time('toBlobSync', () => { p.toBlob(); });
  await time('toBlob', () => p.toBlob());
  await time('thumbBlob', () => p.thumbBlob(480));
  p.destroy(); src.revoke();
  return m;
});
console.log('cpu x' + rate, JSON.stringify(r));
await t.close();
